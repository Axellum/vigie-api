"""Vigicrues collector: the official river flood vigilance of France (SCHAPI) as ``Vigilance`` objects.

Vigicrues (https://www.vigicrues.gouv.fr/), the flood information service of the French State run by the SCHAPI, gives a
colour to each **section** (tronçon) of the rivers it watches: green, yellow, orange or red, for the hours or days to
come. One public GeoJSON flow carries all of them, with the line of every section, without a key:

``https://www.vigicrues.gouv.fr/services/InfoVigiCru.geojson`` (documented at https://www.vigicrues.gouv.fr/services/v1.1,
section "GeoJson", as ``/services/1/InfoVigiCru.geojson``, which redirects to the address above). Its envelope holds
``RefInfoVigiCru`` (the reference of the bulletin, ``20102026_10``) and ``DtHrInfoVigiCru`` (when it was published); each
feature is a section with ``CdEntCru`` (its code), ``lbentcru`` (its name), ``cdensup_1`` (the code of its territory, a
Service de prévision des crues area), ``CdTCC`` (the basin) and ``NivInfViCr`` (the level, 1 to 4).

The levels: 1 green, 2 yellow, 3 orange, 4 red. The flow itself carries only the number; the colours are the ones of the
official local bulletins, which were compared on 2026-10-20 (the sections Vistre and Vidourle at level 3 are "orange" in
the bulletin of the territory Grand Delta, the Gardon d'Alès at level 2 is "Jaune"). **A green section is no warning**: it
is not returned (it is counted in the coverage).

The dataset (https://www.data.gouv.fr/datasets/troncons-de-cours-deau-vigicrues-simplifies-avec-niveau-de-vigilance-crues-2)
says the flow is provided at each publication of the flood vigilance, twice a day (10 a.m. and 4 p.m.) outside floods
and more often during them.

**The flow is heavy and cannot be made lighter at the source** (measured on 2026-10-20): one answer is 2,245,691 bytes
for 337 sections; the server does not compress it (``Accept-Encoding: gzip, deflate, br`` gets the same bytes, with no
``Content-Encoding``), sends no ``ETag`` and no ``Last-Modified`` (so no ``304``), ignores a ``Range`` request (it answers
``200`` with the whole body) and takes no filter (``CdEntVigiCru``, ``TypEntVigiCru`` are ignored). The envelope that tells
which bulletin it is (``RefInfoVigiCru``, ``DtHrInfoVigiCru``) is at the END of the file. The other documented services
(``TerEntVigiCru.json``, ``TronEntVigiCru.json``, ``StatEntVigiCru.json``, see the documentation page above) are
referentials: names, codes and links, no level. The level of a section is in this flow only (the pages of the site
embed it in their HTML; that is not an API). The geometry could be bundled (the IGN Géoplateforme WFS has the sections),
but it would save nothing: the levels come with the geometry, in the same document.

**So the number of times the whole flow is read is what costs, and it is cut to what changes.** The flow changes at each
publication. The national map of the site (``/ftp/img_france.png``) is regenerated by the same publication and, unlike the
flow, has validators: on 2026-10-20 the flow was published at 07:55:15 UTC and the image carried
``Last-Modified: 07:55:36 GMT``, and at 13:57:55 (``Ref`` ``20102026_16``) and 13:58:16. A ``HEAD`` on that image (about 350 bytes) is therefore asked instead: the flow is
read only when the image changed, and at the latest after ``SAFETY_S`` (12 hours) whatever the image says. This is an inference from the site, not a documented contract: the weekly live check
(``tools/check_live_feeds.py``) fails if the image has no validator or no longer follows the flow, and while the image
gives none the whole flow is read every hour (20 minutes while a section is orange or red).

A flood vigilance applies to a river section, a line: a point is matched when it lies within a radius of it
(``river_radius_km`` of the query, 5 km by default, see ``docs/data-sources.md``).
"""

from __future__ import annotations

import asyncio
import json
from dataclasses import dataclass
from typing import Any, Optional

import httpx
from shapely.geometry import shape

from app import clock
from app.attribution import credit_text
from app.collectors.base import BaseCollector, CacheEntry, Collected, Fetched, parse_iso_utc
from app.models.schemas import SeverityLevel
from app.models.vigilance import (
    Vigilance,
    VigilanceArea,
    VigilanceGeocode,
    VigilancePhenomenon,
)

FLOW_URL = "https://www.vigicrues.gouv.fr/services/InfoVigiCru.geojson"
TERRITORY_URL = "https://www.vigicrues.gouv.fr/bulletin_local/{territory}"
MAX_FEATURES = 5_000  # the flow has 337 sections; thousands is a mistake

# The national map of the site, regenerated with each publication of the vigilance (see the module docstring).
SIGNAL_URL = "https://www.vigicrues.gouv.fr/ftp/img_france.png"

# How often the image is asked (HEAD, a few hundred bytes): the delay to notice a publication.
CHECK_CALM_S = 900.0
CHECK_FLOOD_S = 300.0
# The longest the flow is kept without being read again, whatever the image says (the image is not a documented contract).
# The regular bulletins are 6 and 18 hours apart: a day holds one such read besides the two publications.
SAFETY_S = 12 * 3600.0
# Without a usable image (no validator, or it is gone): the flow itself is read this often.
DEGRADED_CALM_S = 3600.0
DEGRADED_FLOOD_S = 1200.0
# The image moved but the flow did not (the flow may come a little after the image): ask again this many times before believing it.
MAX_RETRIES = 3

# Keys of the validators kept with the flow.
SIGNAL_KEY = "image"  # Last-Modified and ETag of the image when the flow was read
FULL_KEY = "read_at"  # wall-clock time the whole flow was last read
RETRY_KEY = "retries"

# ``NivInfViCr`` -> our level. 1 is green (no particular vigilance): kept in the table so that it is known, never returned.
LEVELS: dict[int, SeverityLevel] = {
    1: SeverityLevel.GREEN,
    2: SeverityLevel.YELLOW,
    3: SeverityLevel.ORANGE,
    4: SeverityLevel.RED,
}


@dataclass(frozen=True)
class VigicruesFlow:
    """The river sections above green, and how many sections the flow holds."""

    updated_utc: Optional[int]  # DtHrInfoVigiCru: when the vigilance was published
    reference: Optional[str]  # RefInfoVigiCru
    vigilances: tuple[Vigilance, ...]
    sections: int = 0  # all the sections of the flow, green ones included
    skipped: int = 0  # sections above green that could not be read (no valid line or level)


def derive_level(value: Any) -> Optional[SeverityLevel]:
    """Our level for ``NivInfViCr`` (``None`` if it is not 1 to 4)."""
    if isinstance(value, bool) or not isinstance(value, (int, str)):
        return None
    try:
        return LEVELS.get(int(value))
    except ValueError:
        return None


def _line(geometry: Any) -> Any:
    """The shapely line of a GeoJSON LineString / MultiLineString; ``None`` for anything else or a broken one."""
    if not isinstance(geometry, dict) or geometry.get("type") not in ("LineString", "MultiLineString"):
        return None
    try:
        line = shape(geometry)
    except (ValueError, TypeError, KeyError, IndexError, AttributeError):
        return None
    return None if line.is_empty else line


def parse_flow(payload: Any) -> VigicruesFlow:
    """Parse the flow: the sections above green as warnings. All green is a valid answer (nothing in force)."""
    features = payload.get("features") if isinstance(payload, dict) else None
    if not isinstance(features, list) or len(features) > MAX_FEATURES:
        raise ValueError("Vigicrues answer has no usable 'features' list")
    updated_text = payload.get("DtHrInfoVigiCru") if isinstance(payload.get("DtHrInfoVigiCru"), str) else None
    reference = payload.get("RefInfoVigiCru") if isinstance(payload.get("RefInfoVigiCru"), str) else None
    updated = parse_iso_utc(updated_text)
    credit = credit_text("vigicrues")
    attribution = f"{credit} | Last update of the flow: {updated_text}" if updated_text else credit

    vigilances: list[Vigilance] = []
    skipped = 0
    for feature in features:
        props = feature.get("properties") if isinstance(feature, dict) else None
        if not isinstance(props, dict):
            skipped += 1
            continue
        level = derive_level(props.get("NivInfViCr"))
        if level is SeverityLevel.GREEN:
            continue
        code = props.get("CdEntCru")
        line = _line(feature.get("geometry"))
        if level is None or not isinstance(code, str) or not code or line is None:
            skipped += 1
            continue
        territory = props.get("cdensup_1")
        basin = props.get("CdTCC")
        geocodes = [VigilanceGeocode(scheme="VIGICRUES_SECTION", value=code)]
        if territory not in (None, ""):
            geocodes.append(VigilanceGeocode(scheme="VIGICRUES_TERRITORY", value=str(territory)))
        if basin not in (None, ""):
            geocodes.append(VigilanceGeocode(scheme="VIGICRUES_BASIN", value=str(basin)))
        name = props.get("lbentcru")
        vigilance = Vigilance(
            id=f"vigicrues:{code}",
            source="vigicrues",
            country="FR",
            attribution=attribution,
            identifier=f"{reference}:{code}" if reference else code,
            sent_utc=updated,
            level=level,
            level_original=str(props.get("NivInfViCr")),
            phenomenon=VigilancePhenomenon.FLOOD,
            area=VigilanceArea(
                description=name if isinstance(name, str) else None,
                geocodes=geocodes,
                has_polygon=False,
            ),
            derived=["level", "phenomenon"],  # the flow has no message type: the status is not derived, it is unknown
            link=FLOW_URL,
            web=(TERRITORY_URL.format(territory=territory) + f"#{code}") if territory not in (None, "") else None,
        )
        vigilances.append(vigilance.with_shape(line))
    return VigicruesFlow(
        updated_utc=updated,
        reference=reference,
        vigilances=tuple(vigilances),
        sections=len(features),
        skipped=skipped,
    )


def _is_flood(flow: VigicruesFlow) -> bool:
    """Whether a section is orange or red (the vigilance is then renewed more often)."""
    return any(v.level in (SeverityLevel.ORANGE, SeverityLevel.RED) for v in flow.vigilances)


def _as_float(value: Optional[str]) -> Optional[float]:
    try:
        return float(value) if value is not None else None
    except ValueError:
        return None


class VigicruesCollector(BaseCollector[VigicruesFlow]):
    """The flood vigilance of France: the whole flow (2.2 MB) is read only when a publication changed it.

    Each look is a ``HEAD`` of the national map image; the flow is read when the image changed, when none was read yet,
    or when the safety age is reached. Cached 15 minutes (5 while a section is orange or red) between two looks.
    """

    def __init__(self, http_client: Optional[httpx.AsyncClient] = None) -> None:
        super().__init__(
            provider_id="vigicrues_flow",
            name="Vigicrues flood vigilance (SCHAPI)",
            domain="warnings",
            ttl_seconds=int(CHECK_CALM_S),
            timeout_seconds=20.0,  # 2.2 MB, uncompressed
            http_client=http_client,
        )

    async def fetch_flow(self, allow_stale_on_error: bool = True) -> Fetched[VigicruesFlow]:
        """The sections above green, from the cache while it is fresh, else one look (and the flow if it changed)."""
        return await self.fetch_ex(cache_key="flow", allow_stale_on_error=allow_stale_on_error)

    async def _signal(self, client: httpx.AsyncClient) -> Optional[str]:
        """What the publication image says now (``Last-Modified|ETag``); ``None`` if it gives no validator."""
        resp = await self._head(client, SIGNAL_URL)
        if resp.status_code >= 500:
            resp.raise_for_status()
        if resp.status_code != 200:
            return None
        modified, tag = resp.headers.get("Last-Modified"), resp.headers.get("ETag")
        return f"{modified or ''}|{tag or ''}" if (modified or tag) else None

    async def _collect(self, client: httpx.AsyncClient, **kwargs: Any) -> Collected[VigicruesFlow]:
        previous: Optional[CacheEntry[VigicruesFlow]] = kwargs.get("previous")
        known = previous.validators if previous is not None and previous.validators else {}
        signal = await self._signal(client)
        now = clock.wall()
        if previous is not None and signal is not None and signal == known.get(SIGNAL_KEY):
            read_at = _as_float(known.get(FULL_KEY))
            if read_at is not None and 0 <= now - read_at < SAFETY_S:
                # Nothing was published since: keep the flow, look again later (the cache keeps these validators).
                return Collected(previous.value, fresh_for_s=CHECK_FLOOD_S if _is_flood(previous.value) else CHECK_CALM_S, validators=known)
        resp = await self._get(client, FLOW_URL, headers={"Accept": "application/geo+json, application/json;q=0.9"})
        resp.raise_for_status()
        content = resp.content
        flow = await asyncio.to_thread(lambda: parse_flow(json.loads(content)))
        flood = _is_flood(flow)
        validators = {FULL_KEY: repr(now)}
        if signal is None:
            return Collected(flow, fresh_for_s=DEGRADED_FLOOD_S if flood else DEGRADED_CALM_S, validators=validators)
        validators[SIGNAL_KEY] = signal
        retries = int(known[RETRY_KEY]) if known.get(RETRY_KEY, "").isdigit() else 0
        late = (
            previous is not None
            and known.get(SIGNAL_KEY) is not None
            and signal != known[SIGNAL_KEY]
            and flow.reference is not None
            and (flow.reference, flow.updated_utc) == (previous.value.reference, previous.value.updated_utc)
        )
        if late and retries < MAX_RETRIES:
            # The image moved but the flow did not: the flow may come a little after the image. Remember no image at all,
            # so that the next look reads the flow again whatever the image says, and ask once more.
            validators[SIGNAL_KEY] = ""
            validators[RETRY_KEY] = str(retries + 1)
        return Collected(flow, fresh_for_s=CHECK_FLOOD_S if flood else CHECK_CALM_S, validators=validators)
